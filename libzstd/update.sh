#!/bin/sh
# Vendors libzstd sources: ./update.sh 1.5.7
# Copies lib/{common,compress,decompress,dictBuilder} and the public headers, and generates one wrapper per source file
# (cgo only compiles files in the package directory). The asm wrapper is .sx so that the C compiler assembles it.
set -e
v=${1:?version}
cd "$(dirname "$0")"
t=$(mktemp -d)
curl -sSL "https://github.com/facebook/zstd/releases/download/v$v/zstd-$v.tar.gz" | tar xz -C "$t"
rm -rf lib z_*.c z_*.sx
mkdir lib
for d in common compress decompress dictBuilder; do cp -r "$t/zstd-$v/lib/$d" lib/; done
cp "$t/zstd-$v/lib/"*.h lib/
cp "$t/zstd-$v/LICENSE" lib/LICENSE
echo "$v" > lib/VERSION
for f in lib/*/*.c; do
  d=$(basename "$(dirname "$f")"); n=$(basename "$f" .c)
  printf '// Code generated by update.sh; DO NOT EDIT.\n\n#include "%s"\n' "$f" > "z_${d}_$n.c"
done
printf '// Code generated by update.sh; DO NOT EDIT.\n\n#include "lib/decompress/huf_decompress_amd64.S"\n' > z_huf_amd64.sx
rm -rf "$t"
