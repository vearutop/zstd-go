#!/bin/sh
# Vendors libzstd sources: ./update.sh 1.5.7
# Copies lib/{common,compress,decompress,dictBuilder} and the public headers, and generates one wrapper per source file
# (cgo only compiles files in the package directory). The asm wrapper is .sx so that the C compiler assembles it.
# `go mod vendor` copies only directories that hold Go packages, so lib/ and its subdirectories get a doc.go (build tag
# "required", so never built) and required.go imports them under the same tag; without this a vendored copy lacks the C sources.
set -e
v=${1:?version}
cd "$(dirname "$0")"
t=$(mktemp -d)
curl -sSL "https://github.com/facebook/zstd/releases/download/v$v/zstd-$v.tar.gz" | tar xz -C "$t"
rm -rf lib z_*.c z_*.sx required.go
mkdir lib
for d in common compress decompress dictBuilder; do cp -r "$t/zstd-$v/lib/$d" lib/; done
cp "$t/zstd-$v/lib/"*.h lib/
cp "$t/zstd-$v/LICENSE" lib/LICENSE
echo "$v" > lib/VERSION
for f in lib/*/*.c; do
  d=$(basename "$(dirname "$f")"); n=$(basename "$f" .c)
  printf '// Code generated by update.sh; DO NOT EDIT.\n\n#include "%s"\n' "$f" > "z_${d}_$n.c"
done
printf '// Code generated by update.sh; DO NOT EDIT.\n\n#include "lib/decompress/huf_decompress_amd64.S"\n' > z_huf_amd64.sx
dirs="lib lib/common lib/compress lib/decompress lib/dictBuilder"
for d in $dirs; do
  printf '//go:build required\n\n// Code generated by update.sh; DO NOT EDIT.\n\n// Package %s exists only so that `go mod vendor` copies the C sources in this directory (see ../required.go).\npackage %s\n' \
    "$(basename $d)" "$(basename $d)" > "$d/doc.go"
done
{
  printf '//go:build required\n\n// Code generated by update.sh; DO NOT EDIT.\n\npackage libzstd\n\n'
  printf '// These imports are never built (the "required" tag is not set); they make `go mod vendor` copy the C sources and headers\n'
  printf '// that the cgo files include from these directories, which it would otherwise skip as they hold no buildable Go packages.\n'
  printf 'import (\n'
  for d in $dirs; do printf '\t_ "github.com/vearutop/zstd-go/libzstd/%s"\n' "$d"; done
  printf ')\n'
} > required.go
rm -rf "$t"
